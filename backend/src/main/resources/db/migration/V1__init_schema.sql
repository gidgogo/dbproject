-- ---------------------------------------------------------------------
-- 7. MV 갱신
--   누가: 데이터 적재 담당(data-pipeline/sql/load_data.sql 마지막 줄에서 자동 호출)
--   언제: 경기 데이터를 적재·수정한 직후 한 번. 백엔드는 MV를 읽기만 하고 갱신하지 않는다.
--   CONCURRENTLY: 갱신하는 동안에도 백엔드가 MV를 읽을 수 있다 (MV마다 UNIQUE 인덱스가 있어서 가능)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_refresh_stats() RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
    REFRESH MATERIALIZED VIEW CONCURRENTLY mv_season_batting;
    REFRESH MATERIALIZED VIEW CONCURRENTLY mv_season_pitching;
    REFRESH MATERIALIZED VIEW CONCURRENTLY mv_team_standings;
END;
$$;
COMMENT ON FUNCTION fn_refresh_stats() IS 'MV갱신: 경기 데이터 적재 후 시즌 성적·순위 MV를 다시 계산 (적재 스크립트가 호출, 백엔드는 호출하지 않음)';
