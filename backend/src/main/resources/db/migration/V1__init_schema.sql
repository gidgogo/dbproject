-- =====================================================================
-- 테이블
--   컬럼 COMMENT 형식: '논리명: 설명'  → tools/gen_erd_docs.py 가 이 주석을 읽어
--   보고서 10장(테이블 기술서)을 자동으로 만든다. 주석을 고치면 기술서도 같이 바뀐다.
--
--   FK 참조 무결성 정책 요약 (자세한 이유는 docs/report/07_physical_model.md)
--     · 부모가 사라지면 의미가 없는 기록(경기 → 팀경기기록 → 타자/투수/타석) : ON DELETE CASCADE
--     · 다른 기록이 참조하는 기준 정보(팀, 선수, 코드표)                        : ON DELETE RESTRICT
--     · 없어도 되는 선택 정보(구장)                                            : ON DELETE SET NULL
--     · 식별자 값 수정은 자식에게 전파                                          : ON UPDATE CASCADE
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 기준 정보: 팀, 구장, 팀시즌
-- ---------------------------------------------------------------------
CREATE TABLE team (
    team_id       varchar(2)   NOT NULL CHECK (team_id ~ '^[A-Z]{2}$'),
    team_name     varchar(30)  NOT NULL,
    city          varchar(20)  NOT NULL,
    first_season  integer      NOT NULL CHECK (first_season BETWEEN 1982 AND 2100),
    CONSTRAINT pk_team PRIMARY KEY (team_id)
);
COMMENT ON TABLE  team IS '팀: KBO 구단. 팀명이 바뀌어도 같은 구단이면 하나의 행 (팀명 이력은 team_season)';
COMMENT ON COLUMN team.team_id      IS '팀ID: KBO 팀코드. 구단명이 바뀌어도 유지된다 (SK→SSG도 SK)';
COMMENT ON COLUMN team.team_name    IS '대표팀명: 현재 정식 팀명';
COMMENT ON COLUMN team.city         IS '연고지: 연고 도시';
COMMENT ON COLUMN team.first_season IS '첫시즌: 전신 구단을 포함한 KBO 리그 첫 참가 시즌';

CREATE TABLE stadium (
    stadium_id    integer      GENERATED BY DEFAULT AS IDENTITY,
    stadium_name  varchar(40)  NOT NULL,
    city          varchar(20)  NOT NULL,
    is_dome       boolean      NOT NULL DEFAULT false,
    capacity      integer,
    CONSTRAINT pk_stadium PRIMARY KEY (stadium_id),
    CONSTRAINT uq_stadium_name UNIQUE (stadium_name),
    CONSTRAINT ck_stadium_capacity CHECK (capacity > 0)
);
COMMENT ON TABLE  stadium IS '구장: 경기가 열리는 야구장';
COMMENT ON COLUMN stadium.stadium_id   IS '구장ID: 인조 식별자(자동 증가)';
COMMENT ON COLUMN stadium.stadium_name IS '구장명: 정식 명칭';
COMMENT ON COLUMN stadium.city         IS '지역: 구장 소재 도시';
COMMENT ON COLUMN stadium.is_dome      IS '돔구장여부: 지붕이 있는 구장이면 true';
COMMENT ON COLUMN stadium.capacity     IS '수용인원: 좌석 수 (모르면 NULL)';

CREATE TABLE team_season (
    id                  bigint        GENERATED BY DEFAULT AS IDENTITY,
    team_id             varchar(2)    NOT NULL,
    season              integer       NOT NULL CHECK (season BETWEEN 1982 AND 2100),
    team_name           varchar(30)   NOT NULL,
    short_name          varchar(10)   NOT NULL,
    home_stadium_id     integer,
    CONSTRAINT pk_team_season PRIMARY KEY (id),
    CONSTRAINT uq_team_season_key UNIQUE (team_id, season),
    CONSTRAINT uq_team_season_short UNIQUE (season, short_name),
    CONSTRAINT fk_team_season_team FOREIGN KEY (team_id)
        REFERENCES team (team_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_team_season_stadium FOREIGN KEY (home_stadium_id)
        REFERENCES stadium (stadium_id) ON UPDATE CASCADE ON DELETE SET NULL);
COMMENT ON COLUMN team_season.id IS '일련번호: 인조 식별자(JPA 엔티티 @Id). 업무 키는 uq_team_season_key';
COMMENT ON TABLE  team_season IS '팀시즌: 시즌별 팀명과 홈구장 이력 (초안의 팀명이력 TEAM_NAME_HIST를 확장)';
COMMENT ON COLUMN team_season.team_id         IS '팀ID: 팀(FK)';
COMMENT ON COLUMN team_season.season          IS '시즌: 연도';
COMMENT ON COLUMN team_season.team_name       IS '시즌팀명: 그 시즌의 정식 팀명 (예: 2020 SK 와이번스, 2021 SSG 랜더스)';
COMMENT ON COLUMN team_season.short_name      IS '약칭: 박스스코어·kbodata 팀명 표기 (두산, SSG, 키움 등). 이름→팀ID 매핑 키';
COMMENT ON COLUMN team_season.home_stadium_id IS '홈구장ID: 그 시즌 주 홈구장(FK)';

