CREATE TABLE match (
    match_id         varchar(14)  NOT NULL CHECK (match_id ~ '^[0-9]{8}_[A-Z]{4}[0-9]$'),
    match_date       date         NOT NULL,
    season           integer      NOT NULL GENERATED ALWAYS AS (EXTRACT(YEAR FROM match_date)::integer) STORED CHECK (season BETWEEN 1982 AND 2100),
    away_team_id     varchar(2)   NOT NULL,
    home_team_id     varchar(2)   NOT NULL,
    doubleheader_no  integer      NOT NULL DEFAULT 0,
    series_id        integer      NOT NULL DEFAULT 0,
    stadium_id       integer,
    attendance       integer,
    start_time       time,
    end_time         time,
    duration_min     integer,
    kbo_match_id     varchar(13)  GENERATED ALWAYS AS (replace(match_id::text, '_', '')) STORED,
    CONSTRAINT pk_match PRIMARY KEY (match_id),
    CONSTRAINT uq_match_kbo_match_id UNIQUE (kbo_match_id),
    CONSTRAINT fk_match_away_team_season FOREIGN KEY (away_team_id, season)
        REFERENCES team_season (team_id, season),
    CONSTRAINT fk_match_home_team_season FOREIGN KEY (home_team_id, season)
        REFERENCES team_season (team_id, season),
    CONSTRAINT fk_match_stadium FOREIGN KEY (stadium_id)
        REFERENCES stadium (stadium_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT ck_match_teams CHECK (away_team_id <> home_team_id),
    CONSTRAINT ck_match_doubleheader CHECK (doubleheader_no BETWEEN 0 AND 2),
    CONSTRAINT ck_match_series CHECK (series_id BETWEEN 0 AND 9),
    CONSTRAINT ck_match_attendance CHECK (attendance >= 0),
    CONSTRAINT ck_match_duration CHECK (duration_min > 0),
    -- 경기ID는 날짜·팀·더블헤더를 이어 붙인 "지능형 키"다. 속성과 어긋나지 않도록 검사한다.
    CONSTRAINT ck_match_id_parts CHECK (
        match_id::text = to_char(match_date, 'YYYYMMDD') || '_' || away_team_id || home_team_id || doubleheader_no
    )
);
COMMENT ON TABLE  match IS '경기: 한 경기. 경기ID는 kbodata raw JSON의 id를 그대로 쓴다';
COMMENT ON COLUMN match.match_id         IS '경기ID: YYYYMMDD_원정팀코드홈팀코드더블헤더 (예: 20250601_OBWO0)';
COMMENT ON COLUMN match.match_date       IS '경기일자: 경기 날짜';
COMMENT ON COLUMN match.season          IS '시즌: 경기일자의 연도 (생성 컬럼, 직접 입력 불가)';
COMMENT ON COLUMN match.away_team_id    IS '원정팀ID: (원정팀ID, 시즌)이 팀시즌(FK)';
COMMENT ON COLUMN match.home_team_id    IS '홈팀ID: (홈팀ID, 시즌)이 팀시즌(FK)';
COMMENT ON COLUMN match.doubleheader_no IS '더블헤더번호: 0 일반, 1 1차전, 2 2차전';
COMMENT ON COLUMN match.series_id       IS '경기구분: KBO srId (0 정규시즌, 1 시범경기, 3~7 포스트시즌)';
COMMENT ON COLUMN match.stadium_id      IS '구장ID: 구장(FK). 매핑 실패 시 NULL';
COMMENT ON COLUMN match.attendance      IS '관중수: 명 (무관중 경기는 0)';
COMMENT ON COLUMN match.start_time      IS '개시시각: 경기 시작 시각';
COMMENT ON COLUMN match.end_time        IS '종료시각: 경기 종료 시각';
COMMENT ON COLUMN match.duration_min    IS '경기시간: 분 단위 (3:05 → 185)';
COMMENT ON COLUMN match.kbo_match_id     IS 'KBO경기ID: KBO 게임센터 G_ID (밑줄 제거, 생성 컬럼)';

CREATE TABLE match_team (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY,
    match_id          varchar(14)  NOT NULL,
    team_id           varchar(2)   NOT NULL,
    home_away         varchar(1)   NOT NULL,
    result            varchar(1)   NOT NULL,
    runs              integer      NOT NULL CHECK (runs >= 0),
    hits              integer      NOT NULL CHECK (hits >= 0),
    errors            integer      NOT NULL CHECK (errors >= 0),
    walks_hbp         integer      NOT NULL CHECK (walks_hbp >= 0),
    CONSTRAINT pk_match_team PRIMARY KEY (id),
    CONSTRAINT uq_match_team_key UNIQUE (match_id, team_id),
    CONSTRAINT uq_match_team_side UNIQUE (match_id, home_away),
    CONSTRAINT fk_match_team_match FOREIGN KEY (match_id)
        REFERENCES match (match_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_match_team_team FOREIGN KEY (team_id)
        REFERENCES team (team_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_match_team_side CHECK (home_away IN ('H', 'A')),
    CONSTRAINT ck_match_team_result CHECK (result IN ('W', 'L', 'D')));
COMMENT ON COLUMN match_team.id IS '일련번호: 인조 식별자(JPA 엔티티 @Id). 업무 키는 uq_match_team_key';
COMMENT ON TABLE  match_team IS '팀경기기록: 경기 스코어보드의 팀별 한 줄 (R H E B)';
COMMENT ON COLUMN match_team.match_id   IS '경기ID: 경기(FK)';
COMMENT ON COLUMN match_team.team_id   IS '팀ID: 팀(FK). 그 경기의 홈팀 또는 원정팀이어야 함(트리거로 검사)';
COMMENT ON COLUMN match_team.home_away IS '홈원정구분: H 홈, A 원정. 경기의 팀ID에서 유도되지만 조회 편의를 위해 저장하고 트리거로 일관성을 보장';
COMMENT ON COLUMN match_team.result    IS '승패: W 승, L 패, D 무';
COMMENT ON COLUMN match_team.runs      IS '득점: R';
COMMENT ON COLUMN match_team.hits      IS '안타: H';
COMMENT ON COLUMN match_team.errors    IS '실책: E';
COMMENT ON COLUMN match_team.walks_hbp IS '4사구: B (볼넷+몸에 맞는 공)';

CREATE TABLE inning_score (
