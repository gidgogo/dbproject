-- V1__init_schema.sql : KBO 야구 기록 DB 초기 스키마 (Flyway)
--   팀 레포(gidgogo/KBO) backend/src/main/resources/db/migration 규칙에 맞춘 버전.
--   · JPA ddl-auto=validate 와 맞도록 DOMAIN·smallint·char 를 쓰지 않는다.
--     도메인(값의 범위)은 컬럼 CHECK 로 옮겼고, 정의는 docs/report/09_domain_definition.md 에 남겼다.
--   · 복합 업무키 테이블은 id(bigint IDENTITY)를 PK로 두고 업무키는 UNIQUE(uq_<테이블>_key)로 보장한다.
--     FK는 업무키 UNIQUE를 참조하므로 적재 스크립트는 업무키 그대로 쓴다.
--   · 경기 = match (백엔드 패키지명 player / team / match 와 통일)
--   · Flyway 파일이므로 psql 메타명령(\i, \copy)을 쓰지 않는다. 데이터 적재는 data-pipeline/sql/.
--   · 이미 적용(머지)된 뒤에는 이 파일을 고치지 말고 V3__... 처럼 새 파일로 변경한다.
-- =====================================================================

