-- =====================================================================
-- KBO 야구 기록 DB · 02. 테이블
--   컬럼 COMMENT 형식: '논리명: 설명'  → tools/gen_table_spec.py 가 이 주석을 읽어
--   보고서 10장(테이블 기술서)을 자동으로 만든다. 주석을 고치면 기술서도 같이 바뀐다.
--
--   FK 참조 무결성 정책 요약 (자세한 이유는 docs/report/07_physical_model.md)
--     · 부모가 사라지면 의미가 없는 기록(경기 → 팀경기기록 → 타자/투수/타석) : ON DELETE CASCADE
--     · 다른 기록이 참조하는 기준 정보(팀, 선수, 코드표)                        : ON DELETE RESTRICT
--     · 없어도 되는 선택 정보(구장)                                            : ON DELETE SET NULL
--     · 식별자 값 수정은 자식에게 전파                                          : ON UPDATE CASCADE
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 기준 정보: 팀, 구장, 팀시즌
-- ---------------------------------------------------------------------
CREATE TABLE team (
    team_id       d_team_id     NOT NULL,
    team_name     varchar(30)   NOT NULL,
    city          varchar(20)   NOT NULL,
    first_season  d_season      NOT NULL,
    CONSTRAINT pk_team PRIMARY KEY (team_id)
);
COMMENT ON TABLE  team IS '팀: KBO 구단. 팀명이 바뀌어도 같은 구단이면 하나의 행 (팀명 이력은 team_season)';
COMMENT ON COLUMN team.team_id      IS '팀ID: KBO 팀코드. 구단명이 바뀌어도 유지된다 (SK→SSG도 SK)';
COMMENT ON COLUMN team.team_name    IS '대표팀명: 현재 정식 팀명';
COMMENT ON COLUMN team.city         IS '연고지: 연고 도시';
COMMENT ON COLUMN team.first_season IS '첫시즌: 전신 구단을 포함한 KBO 리그 첫 참가 시즌';

CREATE TABLE stadium (
    stadium_id    smallint      GENERATED BY DEFAULT AS IDENTITY,
    stadium_name  varchar(40)   NOT NULL,
    city          varchar(20)   NOT NULL,
    is_dome       boolean       NOT NULL DEFAULT false,
    capacity      integer,
    CONSTRAINT pk_stadium PRIMARY KEY (stadium_id),
    CONSTRAINT uq_stadium_name UNIQUE (stadium_name),
    CONSTRAINT ck_stadium_capacity CHECK (capacity > 0)
);
COMMENT ON TABLE  stadium IS '구장: 경기가 열리는 야구장';
COMMENT ON COLUMN stadium.stadium_id   IS '구장ID: 인조 식별자(자동 증가)';
COMMENT ON COLUMN stadium.stadium_name IS '구장명: 정식 명칭';
COMMENT ON COLUMN stadium.city         IS '지역: 구장 소재 도시';
COMMENT ON COLUMN stadium.is_dome      IS '돔구장여부: 지붕이 있는 구장이면 true';
COMMENT ON COLUMN stadium.capacity     IS '수용인원: 좌석 수 (모르면 NULL)';

CREATE TABLE team_season (
    team_id          d_team_id    NOT NULL,
    season           d_season     NOT NULL,
    team_name        varchar(30)  NOT NULL,
    short_name       varchar(10)  NOT NULL,
    home_stadium_id  smallint,
    CONSTRAINT pk_team_season PRIMARY KEY (team_id, season),
    CONSTRAINT uq_team_season_short UNIQUE (season, short_name),
    CONSTRAINT fk_team_season_team FOREIGN KEY (team_id)
        REFERENCES team (team_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_team_season_stadium FOREIGN KEY (home_stadium_id)
        REFERENCES stadium (stadium_id) ON UPDATE CASCADE ON DELETE SET NULL
);
COMMENT ON TABLE  team_season IS '팀시즌: 시즌별 팀명과 홈구장 이력 (초안의 팀명이력 TEAM_NAME_HIST를 확장)';
COMMENT ON COLUMN team_season.team_id         IS '팀ID: 팀(FK)';
COMMENT ON COLUMN team_season.season          IS '시즌: 연도';
COMMENT ON COLUMN team_season.team_name       IS '시즌팀명: 그 시즌의 정식 팀명 (예: 2020 SK 와이번스, 2021 SSG 랜더스)';
COMMENT ON COLUMN team_season.short_name      IS '약칭: 박스스코어·kbodata 팀명 표기 (두산, SSG, 키움 등). 이름→팀ID 매핑 키';
COMMENT ON COLUMN team_season.home_stadium_id IS '홈구장ID: 그 시즌 주 홈구장(FK)';

-- ---------------------------------------------------------------------
-- 2. 선수
-- ---------------------------------------------------------------------
CREATE TABLE player (
    player_id           d_player_id    NOT NULL,
    player_name         d_person_name  NOT NULL,
    birth_date          date,
    height_cm           smallint,
    weight_kg           smallint,
    throws              d_hand,
    bats                d_hand,
    position            varchar(10),
    career              varchar(200),
    draft_info          varchar(60),
    draft_year          d_season,
    join_info           varchar(30),
    join_year           d_season,
    signing_bonus_10k   integer,
    is_retired          boolean        NOT NULL DEFAULT false,
    profile_crawled_at  timestamptz,
    CONSTRAINT pk_player PRIMARY KEY (player_id),
    CONSTRAINT ck_player_height CHECK (height_cm BETWEEN 140 AND 230),
    CONSTRAINT ck_player_weight CHECK (weight_kg BETWEEN 40 AND 200),
    CONSTRAINT ck_player_throws CHECK (throws IN ('L', 'R')),
    CONSTRAINT ck_player_position CHECK (position IN ('투수', '포수', '내야수', '외야수')),
    CONSTRAINT ck_player_bonus CHECK (signing_bonus_10k >= 0)
);
COMMENT ON TABLE  player IS '선수: KBO playerId로 식별하는 선수 마스터. 이름은 동명이인·개명이 있어 식별자로 쓰지 않는다';
COMMENT ON COLUMN player.player_id          IS '선수ID: KBO playerId';
COMMENT ON COLUMN player.player_name        IS '선수명: 현재 등록 이름';
COMMENT ON COLUMN player.birth_date         IS '생년월일: 생년월일';
COMMENT ON COLUMN player.height_cm          IS '신장: cm';
COMMENT ON COLUMN player.weight_kg          IS '체중: kg';
COMMENT ON COLUMN player.throws             IS '투구손: L 좌투, R 우투';
COMMENT ON COLUMN player.bats               IS '타격방향: L 좌타, R 우타, S 양타';
COMMENT ON COLUMN player.position           IS '포지션: 투수/포수/내야수/외야수 (상세 페이지 기준)';
COMMENT ON COLUMN player.career             IS '경력: 출신교·경력 원문 (예: 발산초-덕수중-구리인창고). 화면 표시용 문자열';
COMMENT ON COLUMN player.draft_info         IS '지명정보: 지명 순위 원문 (예: 17 KIA 2차 4라운드 34순위)';
COMMENT ON COLUMN player.draft_year         IS '지명연도: 지명정보에서 추출한 연도';
COMMENT ON COLUMN player.join_info          IS '입단정보: 입단년도 원문 (예: 19KIA)';
COMMENT ON COLUMN player.join_year          IS '입단연도: 입단정보에서 추출한 연도';
COMMENT ON COLUMN player.signing_bonus_10k  IS '입단계약금: 만원 단위 (원화가 아니면 NULL)';
COMMENT ON COLUMN player.is_retired         IS '은퇴여부: 은퇴 선수 페이지에서 수집했으면 true';
COMMENT ON COLUMN player.profile_crawled_at IS '프로필수집일시: 상세 페이지를 받은 시각';

CREATE TABLE player_season (
    player_id       d_player_id    NOT NULL,
    season          d_season       NOT NULL,
    team_id         d_team_id      NOT NULL,
    name_in_season  d_person_name  NOT NULL,
    is_batter       boolean        NOT NULL DEFAULT false,
    is_pitcher      boolean        NOT NULL DEFAULT false,
    uniform_no      varchar(3),
    CONSTRAINT pk_player_season PRIMARY KEY (player_id, season, team_id),
    CONSTRAINT fk_player_season_player FOREIGN KEY (player_id)
        REFERENCES player (player_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_player_season_team_season FOREIGN KEY (team_id, season)
        REFERENCES team_season (team_id, season) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_player_season_uniform CHECK (uniform_no ~ '^[0-9]{1,3}$'),
    CONSTRAINT ck_player_season_role CHECK (is_batter OR is_pitcher)
);
COMMENT ON TABLE  player_season IS '선수시즌소속: 선수가 어느 시즌에 어느 팀 소속으로 기록을 남겼는지. 시즌 중 이적하면 팀마다 한 행. 이름+팀+시즌 → 선수ID 매핑의 근거';
COMMENT ON COLUMN player_season.player_id      IS '선수ID: 선수(FK)';
COMMENT ON COLUMN player_season.season         IS '시즌: 연도';
COMMENT ON COLUMN player_season.team_id        IS '팀ID: 소속팀. (팀ID, 시즌)이 팀시즌(FK)';
COMMENT ON COLUMN player_season.name_in_season IS '시즌표기명: 그 시즌 기록실 표기 이름 (개명·외국인 이름 축약 대응)';
COMMENT ON COLUMN player_season.is_batter      IS '타자기록여부: 기록실 타자 목록에 있으면 true';
COMMENT ON COLUMN player_season.is_pitcher     IS '투수기록여부: 기록실 투수 목록에 있으면 true';
COMMENT ON COLUMN player_season.uniform_no     IS '등번호: 상세 페이지에서 수집 (현재 시즌만 확인 가능, 과거 시즌은 NULL)';

CREATE TABLE player_salary (
    player_id       d_player_id  NOT NULL,
    season          d_season     NOT NULL,
    salary_10k_krw  integer,
    salary_usd      integer,
    source_text     varchar(30),
    CONSTRAINT pk_player_salary PRIMARY KEY (player_id, season),
    CONSTRAINT fk_player_salary_player FOREIGN KEY (player_id)
        REFERENCES player (player_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_player_salary_amount CHECK (salary_10k_krw >= 0 AND salary_usd >= 0),
    CONSTRAINT ck_player_salary_any CHECK (salary_10k_krw IS NOT NULL OR salary_usd IS NOT NULL)
);
COMMENT ON TABLE  player_salary IS '선수연봉: 연봉은 팀이 아니라 (선수, 시즌)에 종속되므로 선수시즌소속과 분리 (2NF)';
COMMENT ON COLUMN player_salary.player_id      IS '선수ID: 선수(FK)';
COMMENT ON COLUMN player_salary.season         IS '시즌: 연도';
COMMENT ON COLUMN player_salary.salary_10k_krw IS '연봉(원화): 만원 단위';
COMMENT ON COLUMN player_salary.salary_usd     IS '연봉(달러): 외국인 선수 달러 표기';
COMMENT ON COLUMN player_salary.source_text    IS '연봉원문: 상세 페이지 표기 그대로 (예: 52000만원)';

-- ---------------------------------------------------------------------
-- 3. 경기와 팀 경기 기록
-- ---------------------------------------------------------------------
CREATE TABLE game (
    game_id          d_game_id    NOT NULL,
    game_date        date         NOT NULL,
    season           d_season     NOT NULL GENERATED ALWAYS AS (EXTRACT(YEAR FROM game_date)::smallint) STORED,
    away_team_id     d_team_id    NOT NULL,
    home_team_id     d_team_id    NOT NULL,
    doubleheader_no  smallint     NOT NULL DEFAULT 0,
    series_id        smallint     NOT NULL DEFAULT 0,
    stadium_id       smallint,
    attendance       integer,
    start_time       time,
    end_time         time,
    duration_min     smallint,
    kbo_game_id      varchar(13)  GENERATED ALWAYS AS (replace(game_id::text, '_', '')) STORED,
    CONSTRAINT pk_game PRIMARY KEY (game_id),
    CONSTRAINT uq_game_kbo_game_id UNIQUE (kbo_game_id),
    CONSTRAINT fk_game_away_team_season FOREIGN KEY (away_team_id, season)
        REFERENCES team_season (team_id, season),
    CONSTRAINT fk_game_home_team_season FOREIGN KEY (home_team_id, season)
        REFERENCES team_season (team_id, season),
    CONSTRAINT fk_game_stadium FOREIGN KEY (stadium_id)
        REFERENCES stadium (stadium_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT ck_game_teams CHECK (away_team_id <> home_team_id),
    CONSTRAINT ck_game_doubleheader CHECK (doubleheader_no BETWEEN 0 AND 2),
    CONSTRAINT ck_game_series CHECK (series_id BETWEEN 0 AND 9),
    CONSTRAINT ck_game_attendance CHECK (attendance >= 0),
    CONSTRAINT ck_game_duration CHECK (duration_min > 0),
    -- 경기ID는 날짜·팀·더블헤더를 이어 붙인 "지능형 키"다. 속성과 어긋나지 않도록 검사한다.
    CONSTRAINT ck_game_id_parts CHECK (
        game_id::text = to_char(game_date, 'YYYYMMDD') || '_' || away_team_id || home_team_id || doubleheader_no
    )
);
COMMENT ON TABLE  game IS '경기: 한 경기. 경기ID는 kbodata raw JSON의 id를 그대로 쓴다';
COMMENT ON COLUMN game.game_id         IS '경기ID: YYYYMMDD_원정팀코드홈팀코드더블헤더 (예: 20250601_OBWO0)';
COMMENT ON COLUMN game.game_date       IS '경기일자: 경기 날짜';
COMMENT ON COLUMN game.season          IS '시즌: 경기일자의 연도 (생성 컬럼, 직접 입력 불가)';
COMMENT ON COLUMN game.away_team_id    IS '원정팀ID: (원정팀ID, 시즌)이 팀시즌(FK)';
COMMENT ON COLUMN game.home_team_id    IS '홈팀ID: (홈팀ID, 시즌)이 팀시즌(FK)';
COMMENT ON COLUMN game.doubleheader_no IS '더블헤더번호: 0 일반, 1 1차전, 2 2차전';
COMMENT ON COLUMN game.series_id       IS '경기구분: KBO srId (0 정규시즌, 1 시범경기, 3~7 포스트시즌)';
COMMENT ON COLUMN game.stadium_id      IS '구장ID: 구장(FK). 매핑 실패 시 NULL';
COMMENT ON COLUMN game.attendance      IS '관중수: 명 (무관중 경기는 0)';
COMMENT ON COLUMN game.start_time      IS '개시시각: 경기 시작 시각';
COMMENT ON COLUMN game.end_time        IS '종료시각: 경기 종료 시각';
COMMENT ON COLUMN game.duration_min    IS '경기시간: 분 단위 (3:05 → 185)';
COMMENT ON COLUMN game.kbo_game_id     IS 'KBO경기ID: KBO·네이버 연동용 G_ID (밑줄 제거, 생성 컬럼). 네이버 gameId = KBO경기ID + 시즌';

CREATE TABLE team_game (
    game_id    d_game_id  NOT NULL,
    team_id    d_team_id  NOT NULL,
    home_away  char(1)    NOT NULL,
    result     char(1)    NOT NULL,
    runs       d_count    NOT NULL,
    hits       d_count    NOT NULL,
    errors     d_count    NOT NULL,
    walks_hbp  d_count    NOT NULL,
    CONSTRAINT pk_team_game PRIMARY KEY (game_id, team_id),
    CONSTRAINT uq_team_game_side UNIQUE (game_id, home_away),
    CONSTRAINT fk_team_game_game FOREIGN KEY (game_id)
        REFERENCES game (game_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_team_game_team FOREIGN KEY (team_id)
        REFERENCES team (team_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_team_game_side CHECK (home_away IN ('H', 'A')),
    CONSTRAINT ck_team_game_result CHECK (result IN ('W', 'L', 'D'))
);
COMMENT ON TABLE  team_game IS '팀경기기록: 경기 스코어보드의 팀별 한 줄 (R H E B)';
COMMENT ON COLUMN team_game.game_id   IS '경기ID: 경기(FK)';
COMMENT ON COLUMN team_game.team_id   IS '팀ID: 팀(FK). 그 경기의 홈팀 또는 원정팀이어야 함(트리거로 검사)';
COMMENT ON COLUMN team_game.home_away IS '홈원정구분: H 홈, A 원정. 경기의 팀ID에서 유도되지만 조회 편의를 위해 저장하고 트리거로 일관성을 보장';
COMMENT ON COLUMN team_game.result    IS '승패: W 승, L 패, D 무';
COMMENT ON COLUMN team_game.runs      IS '득점: R';
COMMENT ON COLUMN team_game.hits      IS '안타: H';
COMMENT ON COLUMN team_game.errors    IS '실책: E';
COMMENT ON COLUMN team_game.walks_hbp IS '4사구: B (볼넷+몸에 맞는 공)';

CREATE TABLE inning_score (
    game_id  d_game_id  NOT NULL,
    team_id  d_team_id  NOT NULL,
    inning   d_inning   NOT NULL,
    runs     d_count    NOT NULL,
    CONSTRAINT pk_inning_score PRIMARY KEY (game_id, team_id, inning),
    CONSTRAINT fk_inning_score_team_game FOREIGN KEY (game_id, team_id)
        REFERENCES team_game (game_id, team_id) ON UPDATE CASCADE ON DELETE CASCADE
);
COMMENT ON TABLE  inning_score IS '이닝득점: 스코어보드 이닝별 점수. kbodata의 i_1~i_18 반복 컬럼을 행으로 바꾼 것 (1NF)';
COMMENT ON COLUMN inning_score.game_id IS '경기ID: (경기ID, 팀ID)가 팀경기기록(FK)';
COMMENT ON COLUMN inning_score.team_id IS '팀ID: 공격한 팀';
COMMENT ON COLUMN inning_score.inning  IS '이닝: 1~18';
COMMENT ON COLUMN inning_score.runs    IS '이닝득점: 그 이닝 득점 (공격하지 않은 이닝은 행이 없음)';

-- ---------------------------------------------------------------------
-- 4. 타자 기록과 타석
-- ---------------------------------------------------------------------
CREATE TABLE pa_result_type (
    result_type       varchar(20)  NOT NULL,
    result_type_name  varchar(20)  NOT NULL,
    batted_ball       char(2),
    is_at_bat         boolean      NOT NULL,
    is_hit            boolean      NOT NULL,
    total_bases       smallint     NOT NULL,
    is_walk           boolean      NOT NULL,
    is_hbp            boolean      NOT NULL,
    is_sac_fly        boolean      NOT NULL,
    is_sac_bunt       boolean      NOT NULL,
    is_strikeout      boolean      NOT NULL,
    is_double_play    boolean      NOT NULL,
    CONSTRAINT pk_pa_result_type PRIMARY KEY (result_type),
    CONSTRAINT ck_pa_result_type_bb CHECK (batted_ball IN ('GB', 'FB', 'LD', 'BU')),
    CONSTRAINT ck_pa_result_type_tb CHECK (total_bases BETWEEN 0 AND 4),
    CONSTRAINT ck_pa_result_type_hit CHECK ((total_bases > 0) = is_hit),
    CONSTRAINT ck_pa_result_type_ab CHECK (NOT is_hit OR is_at_bat)
);
COMMENT ON TABLE  pa_result_type IS '타석결과유형: 안타·삼진·땅볼 등 결과 유형과 기록 집계 규칙(타수 포함 여부, 루타 수)';
COMMENT ON COLUMN pa_result_type.result_type      IS '결과유형코드: SINGLE, DOUBLE, STRIKEOUT, GROUND_OUT 등';
COMMENT ON COLUMN pa_result_type.result_type_name IS '결과유형명: 한글 이름';
COMMENT ON COLUMN pa_result_type.batted_ball      IS '타구종류: GB 땅볼, FB 뜬공, LD 직선타, BU 번트 (안타는 kbodata에 정보 없음)';
COMMENT ON COLUMN pa_result_type.is_at_bat        IS '타수포함여부: 타수(AB)에 들어가면 true';
COMMENT ON COLUMN pa_result_type.is_hit           IS '안타여부: 안타면 true';
COMMENT ON COLUMN pa_result_type.total_bases      IS '루타수: 1루타 1 ~ 홈런 4';
COMMENT ON COLUMN pa_result_type.is_walk          IS '볼넷여부: 볼넷·고의4구';
COMMENT ON COLUMN pa_result_type.is_hbp           IS '사구여부: 몸에 맞는 공';
COMMENT ON COLUMN pa_result_type.is_sac_fly       IS '희생플라이여부: 희생플라이';
